#!/usr/bin/env node
/**
 * scrape-htb-avatars.mjs — download the official HTB machine avatar (the
 * transparent "pfp") for every writeup and wire it into the site.
 *
 * HTB's machine API is auth-gated, so this needs an HTB App Token:
 *   HTB → Profile Settings → "App Tokens" → Create  (then copy the JWT)
 *
 * Usage:
 *   HTB_TOKEN='eyJ0eXAi...' node scripts/scrape-htb-avatars.mjs
 *
 * For each writeup it resolves the machine by name, downloads the avatar into
 * public/machines/<slug>.png, and (re)generates src/data/machineAvatars.ts.
 * Machines it can't resolve are skipped (they keep the initials badge).
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, basename } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const WU_DIR = resolve(__dirname, '../src/content/writeups');
const OUT_DIR = resolve(__dirname, '../public/machines');
const MAP_FILE = resolve(__dirname, '../src/data/machineAvatars.ts');
const API = 'https://labs.hackthebox.com/api/v4';

const TOKEN = process.env.HTB_TOKEN;
if (!TOKEN) {
  console.error('Missing HTB_TOKEN. Generate one at HTB → Profile Settings → App Tokens.');
  process.exit(2);
}
const headers = {
  Authorization: `Bearer ${TOKEN}`,
  Accept: 'application/json',
  'User-Agent': 'fletcher-portfolio-avatar-sync',
};

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// read `machine:` + the slug (filename) from each writeup's frontmatter
function writeups() {
  return readdirSync(WU_DIR)
    .filter((f) => f.endsWith('.md'))
    .map((f) => {
      const fm = readFileSync(resolve(WU_DIR, f), 'utf8').split(/^---$/m)[1] || '';
      const m = fm.match(/^\s*machine:\s*["']?(.+?)["']?\s*$/m);
      return { slug: basename(f, '.md'), machine: m ? m[1].trim() : basename(f, '.md') };
    });
}

async function resolveAvatar(name) {
  const res = await fetch(`${API}/machine/profile/${encodeURIComponent(name)}`, { headers });
  if (!res.ok) throw new Error(`profile ${name}: HTTP ${res.status}`);
  const json = await res.json();
  const info = json.info ?? json.data ?? json;
  return info.avatar; // e.g. /storage/avatars/<hash>.png
}

async function download(path, dest) {
  // machine avatars come back as a relative `/avatars/<hash>.png` served from
  // the labs storage bucket; maker/other avatars may already be absolute URLs.
  const url = path.startsWith('http') ? path : `https://labs.hackthebox.com/storage${path}`;
  const res = await fetch(url, { headers });
  if (!res.ok) throw new Error(`avatar: HTTP ${res.status}`);
  writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  const map = {};
  for (const { slug, machine } of writeups()) {
    try {
      const avatar = await resolveAvatar(machine);
      if (!avatar) throw new Error('no avatar field');
      await download(avatar, resolve(OUT_DIR, `${slug}.png`));
      map[slug] = `/machines/${slug}.png`;
      console.log(`✓ ${machine} → /machines/${slug}.png`);
    } catch (e) {
      console.warn(`· skip ${machine}: ${e.message}`);
    }
    await sleep(400); // be gentle on the API
  }

  const body =
    '// Maps a writeup id (slug) -> locally-downloaded official HTB machine avatar\n' +
    '// under /public/machines. Generated by scripts/scrape-htb-avatars.mjs.\n' +
    'export const machineAvatars: Record<string, string> = ' +
    JSON.stringify(map, null, 2) +
    ';\n';
  writeFileSync(MAP_FILE, body);
  console.log(`\nwrote ${Object.keys(map).length} avatars → ${MAP_FILE}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
